def extract_class1_shap_values(
    shap_output,
    expected_shape
):

    # -------------------------------------------------------------------------
    # CASE 1
    # SHAP returns:
    #
    # [
    #     class_0_values,
    #     class_1_values
    # ]
    # -------------------------------------------------------------------------

    if isinstance(
        shap_output,
        list
    ):

        if len(shap_output) != 2:

            raise ValueError(
                "Expected binary classification "
                "SHAP output with 2 classes."
            )

        class1_values = np.asarray(
            shap_output[1],
            dtype=np.float64
        )

        if (
            class1_values.shape
            != expected_shape
        ):

            raise ValueError(
                "Class 1 SHAP shape mismatch.\n"
                f"Expected : {expected_shape}\n"
                f"Found    : {class1_values.shape}"
            )

        return class1_values


    # -------------------------------------------------------------------------
    # Convert to numpy
    # -------------------------------------------------------------------------

    shap_array = np.asarray(
        shap_output,
        dtype=np.float64
    )


    # -------------------------------------------------------------------------
    # CASE 2
    #
    # SHAP output:
    # (samples, features)
    # -------------------------------------------------------------------------

    if shap_array.ndim == 2:

        if (
            shap_array.shape
            == expected_shape
        ):

            return shap_array


    # -------------------------------------------------------------------------
    # CASE 3
    #
    # SHAP output:
    # (samples, features, classes)
    #
    # Example:
    # (500, 66, 2)
    # -------------------------------------------------------------------------

    if shap_array.ndim == 3:

        if (
            shap_array.shape[0]
            == expected_shape[0]
            and
            shap_array.shape[1]
            == expected_shape[1]
            and
            shap_array.shape[2]
            == 2
        ):

            return (
                shap_array[:, :, 1]
            )


        # ---------------------------------------------------------------------
        # CASE 4
        #
        # SHAP output:
        # (classes, samples, features)
        # ---------------------------------------------------------------------

        if (
            shap_array.shape[0] == 2
            and
            shap_array.shape[1]
            == expected_shape[0]
            and
            shap_array.shape[2]
            == expected_shape[1]
        ):

            return (
                shap_array[1]
            )


    # -------------------------------------------------------------------------
    # Unsupported format
    # -------------------------------------------------------------------------

    raise ValueError(
        "\nUnsupported SHAP output format.\n"
        f"SHAP output shape: "
        f"{shap_array.shape}\n"
        f"Expected sample shape: "
        f"{expected_shape}"
    )


